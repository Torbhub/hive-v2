export const GUIDE = `# Stretchtext skims

The reader's terminal shows your reply at skim level first. Detail opens on demand, one piece at a time, from a trailer line. Write the skim only:

- One to three short sentences: the decision, the state, the next action. The skim answers on its own. Target under a third of the original's words.
- Errors, blockers, questions for the reader, and anything security- or money-relevant stay in the skim, always.
- End with a trailer that names the openable parts: \`Details on: A · B · C — say which\`. A part is named in a word or two; its content is not repeated.
- Keep every fact the reader must not lose: decisions, actions, results, file paths, commands, numbers. What leaves the skim leaves a name in the trailer.
- Add nothing new. No markup, no braces.`;
